// Generates this adapter's framework wirings from the shared definitions in
// @learner/server. Nothing here is registered at runtime: the framework's CLI
// inspects these files, so they are plain source with literal names.
//
//   src/generated/functions.gen.ts       one wrapper per shared function (by RPC name)
//   src/generated/workflows/*.gen.ts      each shared workflow body, verbatim
//   src/wirings/generated/http.gen.ts     the shared REST route table
//   src/wirings/generated/queues.gen.ts   the shared queue workers
//   src/wirings/generated/schedules.gen.ts the shared schedules
//
// Wrappers and wirings live in separate files: a function defined beside its
// own wiring is skipped by the inspector. `--check` exits 1 when any output on
// disk is stale.
import { Glob } from 'bun'
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { FUNCTION, type FunctionDefinition } from '@learner/server/runtime/define.js'
import { functionModules } from '@learner/server/functions/registry.gen.js'
import { buildRegistry } from '@learner/server/functions/registry.js'
import { QUEUES, SCHEDULES } from '@learner/server/wiring/queues.js'
import { ROUTES } from '@learner/server/http/routes.js'

const ROOT = resolve(import.meta.dir, '..')
const SERVER_SRC = resolve(ROOT, '../server/src')
const HEADER = '// GENERATED by packages/runtime-pikku/scripts/gen-wiring.ts. Do not edit.'
const outputs = new Map<string, string>()
const emit = (path: string, lines: string[]) => outputs.set(join(ROOT, path), [HEADER, ...lines, ''].join('\n'))

const registry = buildRegistry()
const fileOf = new Map<string, string>()
for (const [file, module] of functionModules) for (const name of Object.keys(module)) if (registry.get(name) === module[name]) fileOf.set(name, file)
const serverImport = (file: string) => `@learner/server/${file.replace(/\.ts$/, '.js')}`
const kindOf = (def: FunctionDefinition) => def[FUNCTION]

// --- function wrappers ------------------------------------------------------
// A route's path parameters are merged into the function's data, so they are
// part of its wire input type.
const pathParams = new Map<string, string[]>()
for (const r of ROUTES) for (const [, p] of r.path.matchAll(/:(\w+)/g)) pathParams.set(r.func, [...(pathParams.get(r.func) ?? []), p!])
// Pikku-native server modules, found by their source, not imported (they import the generated `#pikku` types).
const nativeSources = new Map<string, string>()
for (const file of new Glob('{functions,wirings}/**/*.ts').scanSync(SERVER_SRC)) {
  if (file.endsWith('.test.ts')) continue
  const source = readFileSync(join(SERVER_SRC, file), 'utf8')
  if (/^export const \w+\s*=\s*pikku\w*Func\b/m.test(source)) nativeSources.set(file, source)
}
// Only a workflow body consumes a function's output type (a shared body copied here, or a native body, is typed
// against its steps); everything else reaches a function through JSON.
const workflowSources = [...registry].filter(([, def]) => kindOf(def) === 'workflow').map(([name]) => readFileSync(join(SERVER_SRC, fileOf.get(name)!), 'utf8'))
const nativeWorkflowSources = [...nativeSources.values()].filter((src) => /^export const \w+\s*=\s*pikkuWorkflowFunc\b/m.test(src))
const stepNames = new Set([...workflowSources, ...nativeWorkflowSources].flatMap((src) => [...src.matchAll(/\.do\(\s*(['"])[^'"]*\1\s*,\s*(['"])(\w+)\2/g)].map((m) => m[3]!)))
const scheduled = new Set(SCHEDULES.map((s) => s.func))
const outputType = (name: string) => stepNames.has(name) ? `OutputOf<typeof $${name}>` : 'unknown'
const inputType = (name: string) => {
  const params = pathParams.get(name)
  return params ? `InputOf<typeof $${name}> & { ${params.map((p) => `${p}: string`).join('; ')} }` : `InputOf<typeof $${name}>`
}
const functions = [...registry].filter(([, def]) => kindOf(def) !== 'workflow').sort(([a], [b]) => a.localeCompare(b))
// A shared step's `onError: '<handler>'` has no framework equivalent: the framework
// unwinds a failed run through each completed or failed step's `compensate`,
// newest-first, a step only after every step that started after it. So a
// workflow's handler becomes the compensate of its FIRST step, which the unwind
// reaches last and exactly once, whichever step failed (adapt.ts compensateWith);
// the option itself is stripped from the copied body. One handler per workflow.
const ON_ERROR = /,\s*onError:\s*(['"])(\w+)\1/g
const compensation = new Map<string, string>()
for (const src of workflowSources) {
  const calls = src.split(/\bworkflow\.do\(/).slice(1).map((call) => ({
    rpc: /^\s*(['"])[^'"]*\1\s*,\s*(['"])(\w+)\2/.exec(call)?.[3], handlers: [...call.matchAll(ON_ERROR)].map((m) => m[2]!),
  }))
  const handlers = new Set(calls.flatMap((c) => c.handlers))
  if (!handlers.size) continue
  if (handlers.size > 1) throw new Error(`a workflow names several onError handlers (${[...handlers].join(', ')}); the framework can run one`)
  const first = calls[0]
  if (!first?.rpc || !first.handlers.length) throw new Error(`a workflow with onError must set it on its first step, an RPC step (${first?.rpc ?? 'none'})`)
  const prior = compensation.get(first.rpc)
  if (prior && prior !== first.handlers[0]) throw new Error(`${first.rpc} is the first step of two workflows with different onError handlers`)
  compensation.set(first.rpc, first.handlers[0]!)
}
emit('src/generated/functions.gen.ts', [
  `import { pikkuFunc, pikkuSessionlessFunc } from '#pikku/function'`,
  `import { ${compensation.size ? 'compensateWith, ' : ''}runShared, type InputOf, type OutputOf } from '../adapt.js'`,
  ...functions.map(([name]) => `import { ${name} as $${name} } from '${serverImport(fileOf.get(name)!)}'`),
  '',
  ...functions.map(([name, def]) => {
    const factory = kindOf(def) === 'session' ? 'pikkuFunc' : 'pikkuSessionlessFunc'
    // A schedule runs a function with no data and expects nothing back.
    if (scheduled.has(name)) return `export const ${name} = ${factory}<void, void>({ func: async (services, data, wire) => { await runShared('${name}', $${name}, services, data, wire) } })`
    const expose = def.meta.expose ? 'expose: true, ' : ''
    const handler = compensation.get(name)
    const compensate = handler ? `compensate: (services, _data, wire) => compensateWith('${handler}', $${handler}, services, wire), ` : ''
    return `export const ${name} = ${factory}<${inputType(name)}, ${outputType(name)}>({ ${expose}${compensate}func: (services, data, wire) => runShared('${name}', $${name}, services, data, wire) })`
  }),
])

// --- workflows: the shared body, verbatim ------------------------------------
const workflowFiles = [...new Set([...registry].filter(([, def]) => kindOf(def) === 'workflow').map(([name]) => fileOf.get(name)!))].sort()
const IMPORT = /(from\s+|import\s+)(['"])(\.{1,2}\/[^'"]+)\2/g
for (const file of workflowFiles) {
  const source = readFileSync(join(SERVER_SRC, file), 'utf8')
  const sourceDir = dirname(join(SERVER_SRC, file))
  const body = source
    .replace(/^import\s*\{\s*defineWorkflow\s*\}\s*from\s*['"][^'"]*runtime\/define\.js['"];?\s*$/m, `import { pikkuWorkflowFunc } from '#pikku/workflow/pikku-workflow-types.gen.js'`)
    // auth: false: a run's owner is optional, as under the standalone engine (a queue job or schedule starts runs
    // with none), and every step applies its own access rules (runShared). The framework judges a workflow's auth
    // when its function runs (core 0.12.156), so without it an ownerless run fails with MissingSessionError.
    .replace(/\bdefineWorkflow\(\{/g, 'pikkuWorkflowFunc({ auth: false,')
    .replace(ON_ERROR, '')
    .replace(IMPORT, (_m, lead: string, q: string, spec: string) => `${lead}${q}${serverImport(relative(SERVER_SRC, resolve(sourceDir, spec)).replace(/\.js$/, '.ts'))}${q}`)
  if (/defineWorkflow|runtime\/define\.js/.test(body)) throw new Error(`${file}: could not rewrite its define import`)
  emit(`src/generated/workflows/${file.replace(/^.*\//, '').replace(/\.workflow\.ts$/, '.gen.ts')}`, [`// Source: packages/server/src/${file}`, body.trimEnd()])
}

// --- wirings -----------------------------------------------------------------
// A table entry names a shared function (a generated wrapper) or a Pikku-native one, imported from its own file.
const nativeFile = new Map<string, string>()
for (const [file, source] of nativeSources) for (const [, name] of source.matchAll(/^export const (\w+)\s*=\s*pikku\w*Func\b/gm)) nativeFile.set(name!, file)
const importsOf = (names: string[]) => {
  const byModule = new Map<string, string[]>()
  for (const name of [...new Set(names)].sort()) {
    if (!registry.has(name) && !nativeFile.has(name)) throw new Error(`the tables name ${name}, which no server module exports as a function`)
    const from = registry.has(name) ? '../../generated/functions.gen.js' : serverImport(nativeFile.get(name)!)
    byModule.set(from, [...(byModule.get(from) ?? []), name])
  }
  return [...byModule].map(([from, list]) => `import { ${list.join(', ')} } from '${from}'`)
}
emit('src/wirings/generated/http.gen.ts', [
  `import { wireHTTP } from '#pikku/http'`,
  ...importsOf(ROUTES.map((r) => r.func)),
  ...(ROUTES.some((r) => r.requireApiKey) ? [`import { requireApiKey } from '../../require-api-key.js'`] : []),
  '',
  ...ROUTES.map((r) => `wireHTTP({ method: '${r.method}', route: '${r.path}', ${r.auth === false ? 'auth: false, ' : ''}${r.requireApiKey ? 'middleware: [requireApiKey], ' : ''}func: ${r.func} })`),
])
emit('src/wirings/generated/queues.gen.ts', [
  `import { wireQueueWorker } from '#pikku/queue'`,
  ...importsOf(QUEUES.map((q) => q.func)),
  '',
  ...QUEUES.map((q) => `wireQueueWorker({ name: '${q.queue}', func: ${q.func}, config: ${JSON.stringify(q.config)} })`),
])
emit('src/wirings/generated/schedules.gen.ts', [
  `import { wireScheduler } from '#pikku/scheduler'`,
  ...importsOf(SCHEDULES.map((s) => s.func)),
  '',
  ...SCHEDULES.map((s) => `wireScheduler({ name: '${s.name}', schedule: '${s.cron}', func: ${s.func} })`),
])

// --- write or check -------------------------------------------------------------
const stale = (path: string, body: string) => { try { return readFileSync(path, 'utf8') !== body } catch { return true } }
const generatedDirs = ['src/generated/workflows'].map((d) => join(ROOT, d))
const orphans = generatedDirs.flatMap((d) => { try { return readdirSync(d).map((f) => join(d, f)) } catch { return [] } }).filter((p) => !outputs.has(p))
if (process.argv.includes('--check')) {
  const bad = [...[...outputs].filter(([p, b]) => stale(p, b)).map(([p]) => p), ...orphans]
  if (bad.length) { console.error(`stale wiring (run bun scripts/gen-wiring.ts):\n${bad.map((p) => '  ' + relative(ROOT, p)).join('\n')}`); process.exit(1) }
  console.log(`wiring up to date (${functions.length} functions, ${workflowFiles.length} workflow files, ${ROUTES.length} routes, ${QUEUES.length} queues, ${SCHEDULES.length} schedules)`)
} else {
  for (const p of orphans) rmSync(p)
  // Only stale files are rewritten, so file times say when the wiring last changed.
  const changed = [...outputs].filter(([p, b]) => stale(p, b))
  for (const [path, body] of changed) { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, body) }
  console.log(`wrote ${changed.length + orphans.length}/${outputs.size} files (${functions.length} functions, ${workflowFiles.length} workflow files)`)
}
