// Regenerates packages/server/src/functions/registry.gen.ts: one namespace import
// per function module, so every exported definition is registered under its
// export name. `--check` exits 1 when the file on disk is stale.
import { Glob } from 'bun'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SERVER = join(import.meta.dir, '../packages/server/src')
const OUT = join(SERVER, 'functions/registry.gen.ts')
const files = [...new Glob('{functions,wirings}/**/*.ts').scanSync(SERVER)]
  .filter((f) => !f.endsWith('.test.ts') && !f.endsWith('registry.gen.ts') && !f.endsWith('registry.ts'))
  .filter((f) => /\b(define(Function|SessionlessFunction|VoidFunction|Workflow))\(/.test(readFileSync(join(SERVER, f), 'utf8')))
  .sort()
const rel = (f: string) => './' + f.replace(/^functions\//, '').replace(/^wirings\//, '../wirings/').replace(/\.ts$/, '.js')
const body = [
  '// GENERATED by scripts/gen-registry.ts. Do not edit.',
  ...files.map((f, i) => `import * as m${i} from '${rel(f)}'`),
  '',
  `export const functionModules: ReadonlyArray<readonly [string, Record<string, unknown>]> = [`,
  ...files.map((f, i) => `  ['${f}', m${i}],`),
  ']',
  '',
].join('\n')
if (process.argv.includes('--check')) {
  const current = (() => { try { return readFileSync(OUT, 'utf8') } catch { return '' } })()
  if (current !== body) { console.error('registry.gen.ts is stale: run bun scripts/gen-registry.ts'); process.exit(1) }
  console.log(`registry.gen.ts up to date (${files.length} modules)`)
} else {
  writeFileSync(OUT, body)
  console.log(`wrote ${OUT} (${files.length} modules)`)
}
